"""Developer tool: write docs/GUIDE.md from the guide built into the editor.

The text of the in-app Guide lives in mhqe/guide.py (and the (i) explanations in
mhqe/helptext.py). This script exports it as Markdown so the same text can be read on
GitHub. Run it after changing the guide:

    python tools/build_guide_md.py
"""
from __future__ import annotations

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
from mhqe import guide  # noqa: E402


def slug(title: str) -> str:
    s = re.sub(r"[^a-z0-9 -]", "", title.lower()).strip()
    return re.sub(r"\s+", "-", s)


def to_markdown() -> str:
    pages = guide.pages()
    out = [
        "# MH3U Custom Quest Editor: the guide",
        "",
        "This is the same text as the **Guide** page inside the editor (one tab per chapter below),",
        "exported so it can be read on GitHub. It is generated by `tools/build_guide_md.py`; edit",
        "`mhqe/guide.py` and `mhqe/helptext.py`, not this file.",
        "",
        "Contents: " + " · ".join(f"[{t}](#{slug(t)})" for t, _ in pages),
        "",
    ]
    for title, sections in pages:
        out += [f"## {title}", ""]
        for head, body in sections:
            out += [f"### {head}", ""]
            for para in str(body).split("\n\n"):
                lines = para.split("\n")
                listy = any(re.match(r"\s*(\d+\.|[-*•]) ", ln) or ln.startswith("  ") for ln in lines)
                if listy:
                    out += [ln.rstrip() if ln.strip() else "" for ln in lines]
                    out.append("")
                else:
                    # single line breaks inside a paragraph: keep them as hard breaks
                    out += [("  \n".join(ln.strip() for ln in lines))]
                    out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    path = os.path.join(ROOT, "docs", "GUIDE.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(to_markdown())
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
